class WorldDotsPainter extends CustomPainter {
  final Color color;

  const WorldDotsPainter({required this.color});

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.fill
      ..isAntiAlias = true;

    final double cell = size.width / 90.0;
    final double radius = cell * 0.28;

    for (int r = 0; r < kWorldGrid.length; r++) {
      final String row = kWorldGrid[r];
      final double cy = (r + 0.5) * cell;
      for (int c = 0; c < row.length && c < 90; c++) {
        if (row[c] == '#') {
          final double cx = (c + 0.5) * cell;
          canvas.drawCircle(Offset(cx, cy), radius, paint);
        }
      }
    }
  }

  @override
  bool shouldRepaint(covariant WorldDotsPainter oldDelegate) {
    return oldDelegate.color != color;
  }
}

class WorldDots extends StatelessWidget {
  final double opacity;
  final Color baseColor;

  const WorldDots({
    super.key,
    this.opacity = 0.06,
    this.baseColor = Colors.white,
  });

  @override
  Widget build(BuildContext context) {
    return LayoutBuilder(
      builder: (context, constraints) {
        final double width = constraints.maxWidth;
        final double cell = width / 90.0;
        final double height = cell * 34.0;

        return RepaintBoundary(
          child: CustomPaint(
            size: Size(width, height),
            painter: WorldDotsPainter(
              color: baseColor.withValues(alpha: opacity),
            ),
          ),
        );
      },
    );
  }
}
